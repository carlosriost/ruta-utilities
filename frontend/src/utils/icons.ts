/**
 * Traduccion de las claves de icono guardadas en PostgreSQL a componentes de
 * lucide-react.
 *
 * Para anadir un icono nuevo: usa la clave en `backend/app/seed/content.py` y
 * registrala aqui. Si la clave no existe, se muestra `BookOpen`.
 */
const ICONS: Record<string, LucideIcon> = {
  rocket: Rocket,
  building: Building2,
  shield: ShieldCheck,
  helmet: HardHat,
  lock: Lock,
  clipboard: ListChecks,
  warning: AlertTriangle,
  flag: Flag,
  droplet: Droplet,
  steam: Cloud,
  wind: Wind,
  snowflake: Snowflake,
  flask: FlaskConical,
  bubbles: Droplets,
  energy: Zap,
  gauge: Gauge,
  eye: Eye,
  wrench: Wrench,
  chart: BarChart3,
  list: ListChecks,
  search: Search,
  file: FileText,
  thermometer: Thermometer,
  target: Target,
  phone: PhoneCall,
  trophy: Trophy,
  compass: Compass,
  sparkles: Sparkles,
  award: Award,
  book: BookOpen,
  // Bloques VPO
  flame: Flame,
  truck: Truck,
  mountain: Mountain,
  cylinder: Cylinder,
  siren: Siren,
  users: Users,
  handshake: Handshake,
  scale: Scale,
  health: HeartPulse,
  package: Package,
  car: Car,
}

export function iconFor(key: string | undefined | null): LucideIcon {
  if (!key) return BookOpen
  return ICONS[key] ?? BookOpen
}
